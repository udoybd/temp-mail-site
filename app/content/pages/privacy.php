<p>This policy explains what <?= $e($site) ?> ("we") stores when you use the site, why, and for how long. Short version: we do not want to know who you are, and we delete everything on a timer.</p>
<h2>What we store</h2>
<ul>
<li><strong>A device cookie.</strong> A random value that links this browser to your mailboxes. It contains no personal information.</li>
<li><strong>Your temporary addresses</strong> and when they expire.</li>
<li><strong>Email sent to those addresses</strong>, including attachments, until it expires.</li>
<li><strong>A recovery code</strong>, only if you create one. We store a one-way hash, not the code itself.</li>
<li><strong>Your IP address</strong>, in hashed form, to limit how many new addresses one network can make per day.</li>
<li><strong>Visit statistics, for 30 days.</strong> For each visit we keep your IP address, browser, device type, country, the site you came from, how long you stayed and how many addresses you made. We use it to see how many people use the site and to stop abuse. It is deleted automatically after 30 days and never sold or shared.</li>
</ul>
<p>We do not ask for or store your name, phone number or real email address.</p>
<h2>How long we keep it</h2>
<ul>
<li>Emails: when you delete them, or when the address expires (24 hours at most).</li>
<li>Mailboxes: 24 hours from when they are made.</li>
<li>Accounts with no mailboxes that are unused for 30 days are deleted.</li>
<li>When an address is deleted or expires, its emails are deleted too and the name becomes free for anyone to use again. We keep only a private record of the address name and its times, with no email content.</li>
</ul>
<h2>Third parties</h2>
<ul>
<li><strong>Google AdSense</strong> may show ads on the free site and use cookies to do so. See <a href="https://policies.google.com/technologies/ads" rel="nofollow noopener" target="_blank">how Google uses data</a>.</li>
<li><strong>Google favicon service</strong> loads the small sender icon in your inbox. It receives the sender's domain name and your IP address.</li>
<li>If the site uses Google Analytics, it receives anonymous usage data.</li>
</ul>
<h2>Email content</h2>
<p>We do not read, sell or share the email you receive. Anyone who knows an address cannot open its inbox: only the device that owns it can. HTML email is shown in a sandbox with scripts blocked.</p>
<h2>Your choices</h2>
<p>You can delete any address at any time from the inbox, or delete your whole account on the <a href="/delete-account">Delete account</a> page.</p>
